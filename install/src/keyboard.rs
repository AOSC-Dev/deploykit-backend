use std::{
    fs, io,
    path::{Path, PathBuf},
};

use serde::{Deserialize, Serialize};
use snafu::{ResultExt, Snafu};

const X11_KEYBOARD_CONF: &str = "/etc/X11/xorg.conf.d/00-keyboard.conf";
const VCONSOLE_CONF: &str = "/etc/vconsole.conf";
const KBD_KEYMAPS: &str = "/usr/share/kbd/keymaps";

/// Keyboard layout configuration for the guest environment.
#[derive(Debug, Serialize, Deserialize, Clone, PartialEq, Eq)]
pub struct Keyboard {
    /// XKB layout name, i.e. the value of `XkbLayout` in X11 configuration.
    pub layout: String,
    /// Optional XKB variant name, i.e. the value of `XkbVariant` in X11 configuration.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub variant: Option<String>,
}

impl Default for Keyboard {
    fn default() -> Self {
        Self {
            layout: "us".to_string(),
            variant: None,
        }
    }
}

impl Keyboard {
    fn valid_name(name: &str) -> bool {
        !name.is_empty()
            && name.len() <= 64
            && name
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
    }

    fn validate(&self) -> Result<(), SetKeyboardError> {
        for name in std::iter::once(&self.layout).chain(self.variant.as_ref()) {
            if !Self::valid_name(name) {
                return InvalidNameSnafu { name: name.clone() }.fail();
            }
        }

        Ok(())
    }

    /// The console (virtual terminal) keymap name, if a matching keymap is
    /// installed in the guest environment.
    fn console_keymap(&self) -> Option<String> {
        let candidates = self.variant.iter().chain(std::iter::once(&self.layout));

        for candidate in candidates {
            if find_keymap(candidate) {
                return Some(candidate.clone());
            }
        }

        None
    }
}

#[derive(Debug, Snafu)]
pub enum SetKeyboardError {
    #[snafu(display("Invalid keyboard layout or variant name: {name}"))]
    InvalidName { name: String },
    #[snafu(display("Failed to write keyboard configuration to {}", path.display()))]
    Write { source: io::Error, path: PathBuf },
}

/// Sets the keyboard layout in the guest environment.
/// Must be used in a chroot context.
pub fn set_keyboard(keyboard: &Keyboard) -> Result<(), SetKeyboardError> {
    keyboard.validate()?;

    let config_dir = Path::new(X11_KEYBOARD_CONF).parent().unwrap();
    fs::create_dir_all(config_dir).context(WriteSnafu {
        path: config_dir.to_path_buf(),
    })?;

    fs::write(X11_KEYBOARD_CONF, x11_keyboard_conf(keyboard)).context(WriteSnafu {
        path: PathBuf::from(X11_KEYBOARD_CONF),
    })?;

    if let Some(keymap) = keyboard.console_keymap() {
        let existing = match fs::read_to_string(VCONSOLE_CONF) {
            Ok(content) => Some(content),
            Err(e) if e.kind() == io::ErrorKind::NotFound => None,
            Err(source) => {
                return Err(SetKeyboardError::Write {
                    source,
                    path: PathBuf::from(VCONSOLE_CONF),
                });
            }
        };

        fs::write(
            VCONSOLE_CONF,
            updated_vconsole_conf(existing.as_deref(), &keymap),
        )
        .context(WriteSnafu {
            path: PathBuf::from(VCONSOLE_CONF),
        })?;
    }

    Ok(())
}

/// Generate the Xorg configuration snippet for the given keyboard layout.
fn x11_keyboard_conf(keyboard: &Keyboard) -> String {
    let mut conf = String::from(concat!(
        "# Written by DeployKit, read by systemd-localed(8) and Xorg.\n",
        "# Do not edit this file manually, use localectl(1) instead.\n",
        "Section \"InputClass\"\n",
        "    Identifier \"system-keyboard\"\n",
        "    MatchIsKeyboard \"on\"\n",
    ));
    conf.push_str(&format!(
        "    Option \"XkbLayout\" \"{}\"\n",
        keyboard.layout
    ));
    if let Some(variant) = &keyboard.variant {
        conf.push_str(&format!("    Option \"XkbVariant\" \"{variant}\"\n"));
    }
    conf.push_str("EndSection\n");

    conf
}

/// Update `KEYMAP` in an existing `/etc/vconsole.conf`, preserving other settings.
fn updated_vconsole_conf(existing: Option<&str>, keymap: &str) -> String {
    let mut lines: Vec<String> = existing
        .unwrap_or_default()
        .lines()
        .map(str::to_string)
        .collect();

    let keymap_line = format!("KEYMAP={keymap}");
    let mut found = false;
    for line in &mut lines {
        if line.trim_start().starts_with("KEYMAP=") {
            *line = keymap_line.clone();
            found = true;
        }
    }
    if !found {
        lines.push(keymap_line);
    }

    let mut content = lines.join("\n");
    content.push('\n');

    content
}

/// Recursively look for a keymap with the given name under `/usr/share/kbd/keymaps`.
fn find_keymap(name: &str) -> bool {
    fn walk(dir: &Path, name: &str) -> bool {
        let Ok(entries) = fs::read_dir(dir) else {
            return false;
        };

        for entry in entries.flatten() {
            let Ok(file_type) = entry.file_type() else {
                continue;
            };
            let path = entry.path();

            if file_type.is_dir() {
                if walk(&path, name) {
                    return true;
                }
            } else if let Some(file_name) = path.file_name().and_then(|x| x.to_str()) {
                if file_name == format!("{name}.map") || file_name == format!("{name}.map.gz") {
                    return true;
                }
            }
        }

        false
    }

    walk(Path::new(KBD_KEYMAPS), name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn x11_conf_includes_layout_and_variant() {
        let keyboard = Keyboard {
            layout: "us".to_string(),
            variant: Some("dvorak".to_string()),
        };

        let conf = x11_keyboard_conf(&keyboard);

        assert!(conf.contains("Option \"XkbLayout\" \"us\""));
        assert!(conf.contains("Option \"XkbVariant\" \"dvorak\""));
        assert!(conf.ends_with("EndSection\n"));
    }

    #[test]
    fn x11_conf_omits_missing_variant() {
        let keyboard = Keyboard::default();
        let conf = x11_keyboard_conf(&keyboard);

        assert!(conf.contains("Option \"XkbLayout\" \"us\""));
        assert!(!conf.contains("XkbVariant"));
    }

    #[test]
    fn vconsole_conf_preserves_other_settings() {
        let existing = "FONT=LatArCyrHeb-16\nKEYMAP=us\n";
        let conf = updated_vconsole_conf(Some(existing), "dvorak");

        assert_eq!(conf, "FONT=LatArCyrHeb-16\nKEYMAP=dvorak\n");
    }

    #[test]
    fn vconsole_conf_created_when_missing() {
        let conf = updated_vconsole_conf(None, "us");

        assert_eq!(conf, "KEYMAP=us\n");
    }

    #[test]
    fn deserializes_keyboard() {
        let keyboard: Keyboard =
            serde_json::from_str(r#"{"layout": "us", "variant": "dvorak"}"#).unwrap();

        assert_eq!(keyboard.layout, "us");
        assert_eq!(keyboard.variant.as_deref(), Some("dvorak"));
    }

    #[test]
    fn variant_is_optional() {
        let keyboard: Keyboard = serde_json::from_str(r#"{"layout": "fr"}"#).unwrap();

        assert_eq!(keyboard.layout, "fr");
        assert_eq!(keyboard.variant, None);
    }

    #[test]
    fn invalid_names_are_rejected() {
        let keyboard = Keyboard {
            layout: "us\"; rm -rf /".to_string(),
            variant: None,
        };

        assert!(keyboard.validate().is_err());
    }
}
